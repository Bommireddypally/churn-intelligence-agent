import json
import sys
import time

from agent.db import run_query
from agent.loop import run_agent


CASES_PATH = "evals/cases.json"


def normalize(rows):
    """
    Normalize query results so that we compare values
    rather than row order or column names.

    - Convert each row to a tuple
    - Round floating-point values to 2 decimal places
    - Sort the rows
    """

    normalized = []

    for row in rows:
        normalized_row = []

        for value in row:
            if isinstance(value, float):
                value = round(value, 2)

            normalized_row.append(value)

        normalized.append(tuple(normalized_row))

    return sorted(normalized)


def last_sql(trace):
    """
    Find the last SQL query executed by the agent.
    """

    sqls = [
        action.get("sql")
        for name, action in trace
        if name == "query_customers"
        and action.get("sql")
    ]

    return sqls[-1] if sqls else None


def main(tag: str):
    """
    Run all evaluation cases and calculate the score.
    """

    # Load test cases
    with open(CASES_PATH, encoding="utf-8") as f:
        cases = json.load(f)

    results = []
    auto_total = 0
    auto_passed = 0

    # Run every test case
    for case in cases:

        # Run the agent
        try:
            out = run_agent(case["question"])

        except Exception as e:
            out = {
                "answer": f"AGENT ERROR: {type(e).__name__}",
                "steps": 0,
                "trace": []
            }

        # Get the last SQL query generated by the agent
        sql = last_sql(out["trace"])

        # Store basic result information
        record = {
            "id": case["id"],
            "answer": out["answer"],
            "sql": sql,
            "steps": out["steps"]
        }

        # Manual cases are reviewed by a human
        if case.get("manual"):
            record["passed"] = None

        # Automatically evaluated cases
        else:
            # Run the expected/gold SQL
            gold = run_query(case["gold_sql"])

            # Run the SQL generated by the agent
            if sql:
                got = run_query(sql)
            else:
                got = {
                    "error": "agent ran no query"
                }

            # Compare results
            record["passed"] = (
                "error" not in gold
                and "error" not in got
                and normalize(gold["rows"])
                == normalize(got["rows"])
            )

            auto_total += 1
            auto_passed += int(record["passed"])

        # Save result
        results.append(record)

        # Print result for this case
        print(
            case["id"],
            "->",
            record["passed"]
        )

        # Stay under free-tier rate limits
        time.sleep(3)

    # Print final score
    print(
        f"SCORE ({tag}): "
        f"{auto_passed}/{auto_total}"
    )

    # Save all results to a JSON file
    output_path = f"evals/results_{tag}.json"

    with open(
        output_path,
        "w",
        encoding="utf-8"
    ) as f:
        json.dump(
            results,
            f,
            indent=2
        )

    print(
        f"Results saved to: {output_path}"
    )


if __name__ == "__main__":
    # If a tag is provided:
    #
    # python eval.py improved
    #
    # then tag = "improved"
    #
    # Otherwise use "baseline"

    if len(sys.argv) > 1:
        tag = sys.argv[1]
    else:
        tag = "baseline"

    main(tag)